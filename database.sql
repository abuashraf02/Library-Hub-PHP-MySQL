CREATE DATABASE IF NOT EXISTS library_platform CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE library_platform;
CREATE TABLE IF NOT EXISTS members (
 member_id INT AUTO_INCREMENT PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS books (
 book_id INT AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 author VARCHAR(120) NOT NULL,
 isbn VARCHAR(20) NULL UNIQUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS loans (
 loan_id INT AUTO_INCREMENT PRIMARY KEY,
 member_id INT NOT NULL,
 book_id INT NOT NULL,
 loan_date DATE NOT NULL DEFAULT (CURRENT_DATE),
 due_date DATE NOT NULL,
 CONSTRAINT fk_loan_member FOREIGN KEY (member_id) REFERENCES members(member_id),
 CONSTRAINT fk_loan_book FOREIGN KEY (book_id) REFERENCES books(book_id)
) ENGINE=InnoDB;
